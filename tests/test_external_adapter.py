"""Project-owned (external) adapter loading — the two-repo layout.

The adapter lives in the *project's* repo (``<repo>/.orchestration/``), generated by the
scaffold and loaded by path. Because it is not updated atomically with the engine, the
loader enforces CONTRACT_VERSION and duck-checks the full ProjectConfig surface at load,
so drift fails loudly up front instead of mid-run.
"""

from __future__ import annotations

import json

import pytest

from adapters.project.base import ADAPTER_CONTRACT_VERSION, ProjectConfig
from orchestrator import scaffold
from orchestrator.cli import main as cli
from orchestrator.project_loader import load_project, validate_config
from orchestrator.scaffold import load_kit_manifest, profile_from_languages, scaffold_adapter
from orchestrator.schemas.work import WorkItem
from tests.conftest import make_result


def _scaffold_external(tmp_path, name: str = "my-project"):
    """A project repo with its adapter at <repo>/.orchestration/ (the two-folder layout)."""
    proj = tmp_path / name
    proj.mkdir()
    prof = profile_from_languages(name, ["python"], load_kit_manifest())
    pkg = scaffold_adapter(name, profile=prof, into=proj, package_dir=proj / ".orchestration")
    return proj, pkg


def test_loads_project_owned_adapter_by_path(tmp_path) -> None:
    _, pkg = _scaffold_external(tmp_path)
    cfg = load_project(str(pkg))
    assert cfg.name == "my-project"
    assert isinstance(cfg, ProjectConfig)
    assert validate_config(cfg) == []
    # The profile records the contract the files were generated against.
    assert f"contract_version = {ADAPTER_CONTRACT_VERSION}" in (pkg / "profile.toml").read_text()


def test_contract_mismatch_fails_loudly(tmp_path) -> None:
    _, pkg = _scaffold_external(tmp_path)
    init = pkg / "__init__.py"
    init.write_text(init.read_text().replace(
        f"CONTRACT_VERSION = {ADAPTER_CONTRACT_VERSION}", "CONTRACT_VERSION = 999"))
    with pytest.raises(SystemExit, match="contract"):
        load_project(str(pkg))


def test_missing_contract_declaration_fails_loudly(tmp_path) -> None:
    _, pkg = _scaffold_external(tmp_path)
    init = pkg / "__init__.py"
    init.write_text(init.read_text().replace(
        f"CONTRACT_VERSION = {ADAPTER_CONTRACT_VERSION}", "_UNDECLARED = 0"))
    with pytest.raises(SystemExit, match="CONTRACT_VERSION"):
        load_project(str(pkg))


def test_incomplete_external_adapter_names_missing_members(tmp_path) -> None:
    pkg = tmp_path / ".orchestration"
    pkg.mkdir()
    (pkg / "__init__.py").write_text(
        f"CONTRACT_VERSION = {ADAPTER_CONTRACT_VERSION}\n"
        "class Nearly:\n"
        "    name = 'nearly'\n"
        "def get_config():\n"
        "    return Nearly()\n"
    )
    with pytest.raises(SystemExit, match="install_cmd"):
        load_project(str(pkg))


def test_stale_lint_cmd_mapping_warns_without_blocking(tmp_path, capsys) -> None:
    """#412: an adapter scaffolded before the leg remap keeps a `lint_cmd` no merge gate
    calls and no `types_cmd` at all, so its linter is unverified at merge — and it does not
    self-heal on an engine upgrade. Say so at load. Advisory: the adapter still loads."""
    _, pkg = _scaffold_external(tmp_path, "stale-project")
    cfg_py = pkg / "config.py"
    cfg_py.write_text(
        cfg_py.read_text()
        .replace("def types_cmd(self)", "def lint_cmd(self)")
        .replace("self.types_cmd()", "self.lint_cmd()")
    )

    cfg = load_project(str(pkg))

    assert cfg.name == "stale-project"  # advisory only
    err = capsys.readouterr().err
    assert "lint_cmd" in err and "types_cmd" in err and "orchestrator-scaffold" in err


def test_regenerated_adapter_does_not_warn(tmp_path, capsys) -> None:
    """The control for the warning above: a current adapter is silent, so the warning is a
    signal rather than noise every load prints."""
    _, pkg = _scaffold_external(tmp_path, "fresh-project")
    load_project(str(pkg))
    assert "lint_cmd" not in capsys.readouterr().err


