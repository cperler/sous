def test_cli_drives_a_task_end_to_end_on_a_project_owned_adapter(
    tmp_path, capsys, monkeypatch
) -> None:
    proj, pkg = _scaffold_external(tmp_path)
    tasks = proj / "tasks.json"
    tasks.write_text(json.dumps({"T1": {"title": "wire the thing", "body": "do it"}}))
    monkeypatch.setenv("MY_PROJECT_TASKS", str(tasks))

    # The deterministic intake runner creates a real worktree off HEAD of the CWD repo —
    # make the project dir an isolated git repo and run there, so nothing touches this repo.
    import subprocess

    # Generated adapters run lint/typecheck at REVIEW. Keep those deterministic legs green
    # here: this smoke test exercises CLI plumbing, not the fixture repo's toolchain.
    config_type = type(load_project(str(pkg)))
    monkeypatch.setattr(
        config_type, "_run_gate",
        staticmethod(lambda argv, cwd: subprocess.CompletedProcess(argv, 0, "", "")),
    )
    # Same reason for the #391 worktree hooks: this fixture is a git repo with an adapter
    # in it, not an installed python project, so REVIEW's fresh reinstall has no
    # pyproject.toml to sync and no interpreter here resolves inside the worktree — intake
    # and review would (correctly) refuse. They are REMOVED rather than emptied because
    # mere presence is what routes REVIEW to an origin-verifying lane, and this test wants
    # the plain supervisor path. That the generated adapter DOES declare both is covered in
    # tests/test_bootstrap_scaffold.py.
    assert config_type.fresh_install_paths(config_type)  # not silently absent
    assert config_type.worktree_origin_probes(config_type)
    monkeypatch.delattr(config_type, "fresh_install_paths")
    monkeypatch.delattr(config_type, "worktree_origin_probes")

    for argv in (["git", "init", "-q"], ["git", "add", "-A"],
                 ["git", "-c", "user.email=t@t", "-c", "user.name=t", "commit", "-qm", "init"]):
        subprocess.run(argv, cwd=proj, check=True)
    monkeypatch.chdir(proj)

    base = ["--root", str(tmp_path / "run-root"), "--run", "r1", "--project", str(pkg)]

    def run(*argv):
        assert cli([*base, *argv]) == 0
        out = capsys.readouterr().out.strip()
        return json.loads(out) if out and out != "null" else None

    run("init-run", "--lane", "full")
    run("add-task", "--task", "T1")
    recorded = []
    for _ in range(10):  # safety bound
        work = run("next", "--task", "T1")
        if work is None:
            break
        wi = WorkItem.model_validate(work)
        result_file = tmp_path / "result.json"
        result_file.write_text(make_result(wi).model_dump_json())
        recorded.append(run("record", "--result", str(result_file))["stage"])
    # intake is drained deterministically by `next`, so the supervisor records 5 model stages.
    assert recorded == ["scope", "implement", "test", "deliver", "review"]

    status = run("status")
    assert status["tasks"]["T1"]["state"] == "completed"
    assert (tasks.parent / "completed.log").read_text().startswith("T1")
